"""Глагол первого лица в тексте отчёта."""

import re
from collections.abc import Iterable, Iterator

from nk.core.document import Document, Line
from nk.core.finding import Finding, Severity
from nk.core.rule import rule
from nk.core.standards import Origin
from nk.rules._text import at_sentence_start, is_code, prose

#: Прошедшее время лица не выражает, поэтому список закрытый, а само совпадение
#: берётся только с начала предложения: «Изучил структуру» — это опущенное «я»,
#: а в «Руководитель провёл инструктаж» подлежащее на месте.
PAST = (
    "изучил изучила освоил освоила научился научилась ознакомился ознакомилась "
    "приобрёл приобрел приобрела закрепил закрепила выполнил выполнила "
    "разработал разработала провёл провел провела получил получила "
    "рассмотрел рассмотрела проанализировал проанализировала "
    "участвовал участвовала посетил посетила понял поняла "
    "столкнулся столкнулась убедился убедилась "
    "сделал сделала написал написала создал создала"
)

#: То же во множественном числе: авторское «мы», ловится по параметру.
PAST_PLURAL = (
    "изучили освоили научились ознакомились приобрели закрепили выполнили "
    "разработали провели получили рассмотрели проанализировали участвовали "
    "посетили поняли столкнулись убедились сделали написали создали"
)

#: Настоящее и будущее время: форма первого лица однозначна, и где она стоит,
#: неважно. Окончание признаком не годится — на «-ю» кончается и винительный
#: падеж существительного, поэтому здесь тоже список.
PRESENT = (
    "считаю полагаю думаю предлагаю отмечу опишу приведу покажу рассмотрю "
    "использую применяю изучаю планирую хочу"
)

#: То же во множественном числе: авторское «мы», ловится по параметру.
PRESENT_PLURAL = (
    "считаем полагаем предлагаем отметим опишем приведём приведем покажем "
    "рассмотрим используем применяем изучаем планируем получим определим сделаем"
)


def _pattern(words: str) -> re.Pattern[str]:
    return re.compile(r"\b(?:" + "|".join(sorted(set(words.split()))) + r")\b", re.IGNORECASE)


_PAST = _pattern(PAST)
_PAST_ANY = _pattern(f"{PAST} {PAST_PLURAL}")
_PRESENT = _pattern(PRESENT)
_PRESENT_ANY = _pattern(f"{PRESENT} {PRESENT_PLURAL}")


@rule(
    id="first-person-verb",
    origin=Origin.REGULATION,
    severity=Severity.WARNING,
    title="Текст изложен от первого лица: глагол",
    params={"plural": False},
    allow_missing_suggestion=True,
)
def first_person_verb(doc: Document) -> Iterable[Finding]:
    """Ищет глаголы первого лица там, где местоимения нет: «Научился работать
    с осциллографом», «считаю целесообразным». Прошедшее время берётся только
    с начала предложения — лица оно не выражает, и опущенное подлежащее видно
    лишь по началу фразы. Формулы, буквальные вставки и листинги не проверяются.

    Авторское «мы» — «рассмотрим», «получим» — по умолчанию не трогается:
    часть руководителей его требует. Включается параметром `plural`.

    Безличного изложения ни один стандарт не требует: это требование положений
    вузов и методических указаний. Предъявляют его почти везде, поэтому правило
    включено по умолчанию.

    ## Почему это замечание

    Отчёт излагают безлично: сообщается, что сделано, а не кем. Опущенное «я»
    от произнесённого не отличается — «Освоил методику измерений» остаётся
    рассказом о себе.

    ## Как исправить

    Переписать предложение безличной или страдательной конструкцией: «Освоил
    методику измерений» → «методика измерений освоена», «считаю
    целесообразным» → «целесообразно».
    """
    plural = bool(first_person_verb.params(doc)["plural"])
    for line, found, col in _verbs(doc, plural):
        elided = found[0].isupper()
        yield first_person_verb.finding(
            doc,
            line,
            message=(
                f"Подлежащее опущено: «{found}» читается как «я {found.lower()}»."
                if elided
                else f"Глагол «{found}» стоит в форме первого лица."
            ),
            requirement=(
                "Отчёт излагают безлично: без глаголов первого лица и без опущенного "
                "подлежащего при них."
            ),
            col=col,
        )


def _verbs(doc: Document, plural: bool) -> Iterator[tuple[Line, str, int]]:
    past = _PAST_ANY if plural else _PAST
    present = _PRESENT_ANY if plural else _PRESENT
    for line in doc.iter_lines():
        if is_code(doc, line):
            continue
        text = prose(doc, line)
        for match in present.finditer(text):
            yield line, match.group(), match.start() + 1
        for match in past.finditer(text):
            # Предложение со строчной не начинается: там глагол при подлежащем.
            if match.group()[0].isupper() and at_sentence_start(text, match.start()):
                yield line, match.group(), match.start() + 1
