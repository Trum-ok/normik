"""Оценка вместо измеримого показателя."""

from collections.abc import Iterable

from nk.core.document import Document
from nk.core.finding import Finding, Severity
from nk.core.rule import rule
from nk.core.standards import Origin
from nk.rules._wording import HARD, SIBILANT, VELAR, forms, mentions, pattern, terms

#: Оценочные прилагательные: основа и окончания, которые она принимает.
ADJECTIVES: dict[str, str] = {
    "хорош": SIBILANT,
    "лучш": SIBILANT,
    "худш": SIBILANT,
    "плох": VELAR,
    "гибк": VELAR,
    "удобн": HARD,
    "эффективн": HARD,
    "оптимальн": HARD,
    "современн": HARD,
    "надёжн": HARD,
    "прост": HARD,
    "мощн": HARD,
    "качественн": HARD,
    "удачн": HARD,
    "отличн": HARD,
    "прекрасн": HARD,
    "замечательн": HARD,
    "красив": HARD,
    "уникальн": HARD,
    "идеальн": HARD,
    "интуитивн": HARD,
    "дружественн": HARD,
    "передов": HARD,
    "прогрессивн": HARD,
}

#: Наречия, краткие формы и сравнительная степень: беглая гласная у каждого
#: слова своя, поэтому они перечислены, а не собраны из основы.
ADVERBS = (
    "хорошо хорош хороша хороши плохо плох плоха плохи "
    "удобно удобен удобна удобны эффективно эффективен эффективна эффективны "
    "надёжно надёжен надёжна надёжны просто прост проста просты "
    "качественно мощно мощен мощна мощны оптимально современно "
    "уникально идеально красиво отлично прекрасно замечательно удачно "
    "лучше хуже"
)

#: Устойчивые сочетания, в которых слово — часть термина, а не оценка.
TERMS = (
    r"эффективн\w* (?:значени|мощност|площад|ток|напряжени|сечени|масс|температур"
    r"|скорост|дальност|доз)\w*",
    r"отличн\w* от",
    r"(?:хорошо|плохо) обусловлен\w*",
    r"прост\w* (?:числ|итерац|замен|дроб|множител)\w*",
    r"качественн\w* (?:анализ|оценк|показател|состав|реакци|характер)\w*",
    r"оптимальн\w* (?:управлени|фильтр)\w*",
    r"оптимальн\w* по Парето",
    r"современн\w* состояни\w*",
)

_WORDS = pattern(forms(ADJECTIVES), ADVERBS)
_TERMS = terms(*TERMS)


@rule(
    id="evaluative-word",
    origin=Origin.REGULATION,
    severity=Severity.WARNING,
    title="Свойство названо оценкой, а не показателем",
    params={"headings": False, "allow": []},
)
def evaluative_word(doc: Document) -> Iterable[Finding]:
    """Ищет оценочные слова: «хорошо», «удобный», «эффективный», «современный».
    Формулы, листинги, список источников и рубрикация не проверяются.

    Слово, стоящее в термине, замечанием не считается: «эффективное значение
    напряжения», «отличная от нуля величина», «простые числа», «качественный
    анализ». Перечень терминов правило знает, а тему работы, где оценка
    закреплена утверждённым названием, обходит вместе с рубрикацией.

    Слово, которое на кафедре считают термином, добавляется параметром `allow`
    началом слова: `allow = ["эффективн", "оптимальн"]`. Проверку заголовков
    включает параметр `headings`: по умолчанию правило их не трогает, потому что
    «Современные методы решения задачи» — обычное название обзорного раздела.

    Числа замечание не снимают: «программа объёмом 300 строк работает хорошо»
    так и осталось без показателя. Мера, которой число помогает, — забота
    правила `vague-quantifier`.

    ## Почему это замечание

    Оценка не проверяется: «хорошо» у автора и у рецензента разное, а сравнить
    их нечем. Отчёт сообщает, что измерено и чему равно, — тогда результат можно
    воспроизвести и оспорить.

    ## Как исправить

    Назвать показатель, его значение и условия измерения: «работает хорошо» →
    «время отклика не превышает 40 мс при 100 запросах в секунду».
    """
    params = evaluative_word.params(doc)
    found = mentions(
        doc,
        _WORDS,
        exceptions=_TERMS,
        allow=params["allow"],
        headings=bool(params["headings"]),
    )
    for mention in found:
        yield evaluative_word.finding(
            doc,
            mention.line,
            message=f"Свойство названо оценкой «{mention.found}», а не показателем.",
            requirement=(
                "Свойства и результаты в отчёте описывают измеримо: называют показатель "
                "и его значение, а не дают оценку."
            ),
            suggestion=(
                f"Назвать вместо «{mention.found}» показатель со значением: "
                "«время отклика не превышает 40 мс»."
            ),
            col=mention.col,
        )
