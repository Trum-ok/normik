"""Источники требований.

Правило проверяет требование, а не стандарт: одно и то же требование к подписи
рисунка записано и в ГОСТ 7.32-2017, и в ГОСТ Р 2.105-2019, только под разными
пунктами. Поэтому правило объявляет карту «стандарт — пункт», а какой из них
попадёт в находку, решает профиль.

Пункт может задать и профиль: положение вуза — тоже источник требований, со
своей нумерацией. Такой источник объявляется в самом профиле, см.
:mod:`nk.core.profile`.

Стандарт бывает не активным, а привлечённым: положение вуза требует оформить
список источников по ГОСТ Р 7.0.100-2018, оставаясь при этом отчётом по
ГОСТ 7.32-2017. Такие стандарты профиль перечисляет ключом ``references``, и их
пункты действуют наравне с пунктами активного.

Откуда требование взялось вообще, правило объявляет само — перечислением
:class:`Origin`.
"""

from dataclasses import dataclass
from enum import StrEnum


class Origin(StrEnum):
    """Чьё требование проверяет правило.

    Отвечает на вопрос «кто этого требует», а не «включать ли правило»: шумное
    требование выключают ``default_off`` независимо от происхождения.
    """

    STANDARD = "standard"
    """Записано в стандарте: под стандартом, где пункта нет, правило молчит."""

    UNIVERSAL = "universal"
    """Не записано нигде, но нужно всем: типографика и набор.

    Пункт у такого требования иногда всё же находится — тогда он уточняет
    источник находки, но области правила не сужает.
    """

    REGULATION = "regulation"
    """Устанавливает источник вне стандартов: положение вуза, методические
    указания кафедры, обычай нормоконтроля.

    Стандарт тут ни при чём, поэтому правило работает под любым, а чьё это
    требование и под каким пунктом — знает только профиль.
    """


#: Как происхождение требования называют в документации и в выводе.
ORIGIN_LABELS: dict[Origin, str] = {
    Origin.STANDARD: "стандарт",
    Origin.UNIVERSAL: "общее",
    Origin.REGULATION: "положение вуза",
}


class UnknownStandardError(ValueError):
    """Профиль назвал стандарт, которого нет."""


@dataclass(frozen=True, slots=True)
class Standard:
    id: str
    """Короткое имя: им профиль называет активный стандарт, им же правило ключует пункты."""

    title: str
    """Как стандарт называется в находке и в документации."""

    referenced: bool = False
    """Стандарт не задаёт оформление отчёта, а привлекается другим источником.

    Библиографическое описание своего отчёта не оформляют: по ГОСТ Р 7.0.100
    оформляют список источников в отчёте, составленном по ГОСТ 7.32 или по
    положению вуза. Такой стандарт профиль называет ключом ``references``,
    активным он быть не может — под ним замолчали бы все остальные правила.
    """


G732 = Standard("G732", "ГОСТ 7.32-2017")
GR2105 = Standard("GR2105", "ГОСТ Р 2.105-2019")
GR70100 = Standard("GR70100", "ГОСТ Р 7.0.100-2018", referenced=True)

STANDARDS: dict[str, Standard] = {item.id: item for item in (G732, GR2105, GR70100)}

#: Стандарт, по которому проверяется отчёт, пока профиль не сказал иначе.
DEFAULT = G732

#: Пункта нет: требование не из стандарта — типографика, внутренние диагностики.
NO_CLAUSE = ""


def get(standard_id: str) -> Standard:
    try:
        return STANDARDS[standard_id]
    except KeyError:
        allowed = ", ".join(sorted(STANDARDS))
        raise UnknownStandardError(
            f"неизвестный стандарт {standard_id!r}, допустимы: {allowed}"
        ) from None
