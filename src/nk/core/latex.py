"""Лексика LaTeX, общая парсеру и правилам.

Аргумент ``\\verb`` и его родни (``\\lstinline``, ``\\mintinline``) ограничен
не скобками, а произвольным знаком сразу за именем команды. Разбирать это
приходится и парсеру — чтобы не срезать по проценту внутри такого аргумента, —
и правилам типографики, чтобы не править набранное буквально.
"""

VERB = "verb"


def literal_end(text: str, index: int) -> int | None:
    """Позиция сразу за буквальным аргументом либо ``None``, если его нет.

    ``index`` указывает на знак сразу за именем команды. Буква разделителем быть
    не может: там начинается уже другая команда, а не буквальный аргумент.
    Незакрытый аргумент тянется до конца текста: LaTeX на нём всё равно падает,
    а резать по знакам внутри него неверно.
    """
    while index < len(text) and text[index].isspace():
        index += 1
    if index >= len(text) or text[index].isalpha():
        return None
    close = text.find(text[index], index + 1)
    return len(text) if close == -1 else close + 1
